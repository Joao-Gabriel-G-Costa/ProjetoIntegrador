    private void jButtonConfirmacaoActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_jButtonConfirmacaoActionPerformed
        // TODO add your handling code here:
         int linha = jTableSaidaVeiculos.getSelectedRow();
        if (linha != -1) {
            String idStr = jTableSaidaVeiculos.getValueAt(linha, 0).toString();

            if (telaMovimento != null) {  // ← VERIFICA se tem referência
                telaMovimento.setIdVeiculoSelecionado(idStr);  // ← ENVIA o ID
            }

            dispose();  // fecha a tela
        } else {
            JOptionPane.showMessageDialog(this, "Selecione um veículo.");
        }
    }//GEN-LAST:event_jButtonConfirmacaoActionPerformed


    private void carregarTabelaVeiculos() {
    try {
        VeiculosDAO dao = new VeiculosDAO();
        ArrayList<Veiculos> lista = dao.listaVeiculos();
        DefaultTableModel modelo = (DefaultTableModel) jTableSaidaVeiculos.getModel();
        modelo.setRowCount(0);
        for (Veiculos v : lista) {
            modelo.addRow(new Object[]{
                v.getIdVeiculo(),
                v.getPlaca(),
                v.getMarca(),
                v.getModelo(),
                v.getAnoFabricacao(),
                v.isSituacao() ? "Ativo" : "Inativo"
            });
        }
    } catch (Exception e) {
        JOptionPane.showMessageDialog(this, "Erro ao carregar veículos: " + e.getMessage());
    }
 

    }

