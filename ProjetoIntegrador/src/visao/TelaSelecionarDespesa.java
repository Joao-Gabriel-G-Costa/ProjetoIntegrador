    private void jButtonConfirmacaoActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_jButtonConfirmacaoActionPerformed
        // TODO add your handling code here:
        int linha = jTableSaidaDespesa.getSelectedRow();
        if (linha != -1) {
            String idStr = jTableSaidaDespesa.getValueAt(linha, 0).toString();

            if (telaMovimento != null) {  // ← VERIFICA se tem referência
                telaMovimento.setIdDespesaSelecionada(idStr);  // ← ENVIA o ID
            }

            dispose();  // fecha a tela
        } else {
            JOptionPane.showMessageDialog(this, "Selecione um veículo.");
        }
    }//GEN-LAST:event_jButtonConfirmacaoActionPerformed

   private void carregarTabelaDespesas() {
    try {
        DespesasDAO dao = new DespesasDAO();
        ArrayList<Despesas> lista = dao.listaDeTiposDeDespesas();
        DefaultTableModel modelo = (DefaultTableModel) jTableSaidaDespesa.getModel();
        modelo.setRowCount(0);
        for (Despesas d : lista) {
            modelo.addRow(new Object[]{
                d.getID(),
                d.getDescricao()
            });
        }
    } catch (Exception e) {
        JOptionPane.showMessageDialog(this, "Erro ao carregar despesas: " + e.getMessage());
    }
}

